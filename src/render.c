/* render.c - gqlgw.lua (runtime configuration of the Lua side) and the nginx
 * configuration generated from gqlgw.toml. */
#include <arpa/inet.h>
#include <stdio.h>
#include <string.h>
#include <strings.h>

#include "config.h"

/* ---- Lua --------------------------------------------------------------- */

static void lua_str(gql_buf *b, const char *s)
{
    buf_putc(b, '"');
    for (; *s; s++) {
        unsigned char ch = (unsigned char)*s;
        if (ch == '"' || ch == '\\')
            buf_printf(b, "\\%c", ch);
        else if (ch < 0x20 || ch == 0x7f)
            buf_printf(b, "\\%03u", ch);
        else
            buf_putc(b, (char)ch);
    }
    buf_putc(b, '"');
}

static void lua_num(gql_buf *b, double v)
{
    buf_printf(b, "%.15g", v);
}

static void lua_list(gql_buf *b, const cfg_list *l)
{
    uint32_t i;
    buf_puts(b, "{ ");
    for (i = 0; i < l->n; i++) {
        lua_str(b, l->v[i]);
        buf_puts(b, ", ");
    }
    buf_putc(b, '}');
}

void gqlgw_render_lua(const gqlgw_config *c, const char *src_name, gql_buf *b)
{
    uint32_t i;
    buf_printf(b, "-- generated by gqlc render from %s: do not edit\n", src_name);
    buf_puts(b, "return {\n  schema = ");
    lua_str(b, c->gw.schema);
    if (c->gw.routes) {
        buf_puts(b, ",\n  routes = ");
        lua_str(b, c->gw.routes);
    }
    buf_puts(b, ",\n  lib = ");
    lua_str(b, c->gw.lib);
    buf_printf(b, ",\n  introspection = %s,\n  strict_path_args = %s,\n  debug_headers = %s,\n",
               c->gw.introspection ? "true" : "false", c->gw.strict_path_args ? "true" : "false",
               c->gw.debug_headers ? "true" : "false");
    buf_printf(b, "  max_body_bytes = %lld,\n  max_query_bytes = %lld,\n  max_tokens = %lld,\n  max_depth = %lld,\n"
               "  max_errors = %lld,\n  max_plan_fields = %lld,\n  max_memory = %lld,\n  max_rounds = %lld,\n"
               "  max_fetches = %lld,\n  concurrency = %lld,\n  max_response_bytes = %lld,\n",
               (long long)c->gw.max_body.bytes, (long long)c->lim.query_bytes, (long long)c->lim.tokens,
               (long long)c->lim.depth, (long long)c->lim.errors, (long long)c->lim.plan_fields,
               (long long)c->lim.memory.bytes, (long long)c->lim.rounds, (long long)c->lim.fetches,
               (long long)c->lim.concurrency, (long long)c->lim.response_bytes.bytes);
    buf_puts(b, "  cache_negative_ttl = ");
    lua_num(b, c->cache.negative_ttl);
    buf_puts(b, ",\n  ctype_var = true,\n  cache = {\n");
    if (c->cache.shm_size.bytes > 0)
        buf_puts(b, "    shm = \"gqlgw_cache\",\n");
    buf_printf(b, "    l1_size = %lld,\n    l1_ttl = ", (long long)c->cache.l1_size);
    lua_num(b, c->cache.l1_ttl);
    buf_puts(b, ",\n    l2_ttl = ");
    lua_num(b, c->cache.l2_ttl);
    buf_puts(b, ",\n    gen_ttl = ");
    lua_num(b, c->cache.gen_ttl);
    buf_puts(b, ",\n    down_ttl = ");
    lua_num(b, c->cache.down_ttl);
    buf_puts(b, ",\n    private_header = ");
    lua_str(b, c->cache.private_header);
    buf_puts(b, ",\n    prefix = ");
    lua_str(b, c->cache.prefix);
    buf_puts(b, ",\n");
    if (c->cache.memcached) {
        buf_puts(b, "    memcached = { ");
        if (c->cache.socket) {
            buf_puts(b, "socket = ");
            lua_str(b, c->cache.socket);
        } else {
            buf_puts(b, "host = ");
            lua_str(b, c->cache.host);
            buf_printf(b, ", port = %lld", (long long)c->cache.port);
        }
        buf_printf(b, ", timeout = %lld, pool_size = %lld, keepalive = %lld },\n", (long long)c->cache.timeout,
                   (long long)c->cache.pool_size, (long long)c->cache.keepalive);
    }
    buf_puts(b, "  },\n  sources = { ");
    for (i = 0; i < c->nsources; i++) {
        lua_str(b, c->sources[i].name);
        buf_puts(b, ", ");
    }
    buf_puts(b, "},\n");
    if (c->metrics.enabled) {
        buf_puts(b, "  metrics = {\n    shm = \"gqlgw_metrics\",\n    exclude_operations = ");
        lua_list(b, &c->metrics.exclude_operations);
        buf_puts(b, ",\n    buckets = { ");
        for (i = 0; i < c->metrics.nbuckets; i++) {
            lua_num(b, c->metrics.buckets[i]);
            buf_puts(b, ", ");
        }
        buf_puts(b, "},\n  },\n");
    }
    buf_puts(b, "}\n");
}

/* ---- nginx ------------------------------------------------------------- */

/* quoted nginx string; with dollar = 1, '$' is written as ${gqlgw_dollar}
 * (a literal '$' cannot be escaped in values that support variables) */
static void ngx_q(gql_buf *b, const char *s, int dollar)
{
    buf_putc(b, '"');
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            buf_printf(b, "\\%c", *s);
        else if (*s == '$' && dollar)
            buf_puts(b, "${gqlgw_dollar}");
        else
            buf_putc(b, *s);
    }
    buf_putc(b, '"');
}

static int needs_dollar(const gqlgw_config *c)
{
    uint32_t i, k;
    for (i = 0; i < c->nsources; i++)
        for (k = 0; k < c->sources[i].set_headers.n; k++)
            if (strchr(c->sources[i].set_headers.v[k], '$'))
                return 1;
    return 0;
}

static int in_list(const cfg_list *l, const char *name)
{
    uint32_t i;
    for (i = 0; i < l->n; i++)
        if (!strcasecmp(l->v[i], name))
            return 1;
    return 0;
}

static int in_map(const cfg_map *m, const char *name)
{
    uint32_t i;
    for (i = 0; i < m->n; i++)
        if (!strcasecmp(m->k[i], name))
            return 1;
    return 0;
}

/* $http_x_api_key for X-Api-Key */
static void http_var(gql_buf *b, const char *name)
{
    buf_puts(b, "$http_");
    for (; *name; name++)
        buf_putc(b, *name == '-' ? '_' : (char)((*name >= 'A' && *name <= 'Z') ? *name + 32 : *name));
}

static void render_resolver(const gqlgw_config *c, gql_buf *b, const char *ind)
{
    uint32_t i;
    buf_printf(b, "%sresolver", ind);
    for (i = 0; i < c->ngx.resolver.n; i++)
        buf_printf(b, " %s", c->ngx.resolver.v[i]);
    buf_printf(b, " valid=%s%s;\n", c->ngx.resolver_valid, c->ngx.resolver_ipv6 ? "" : " ipv6=off");
}

/* memcached given by host name: cosockets resolve it with the location's resolver */
static int memcached_needs_resolver(const gqlgw_config *c)
{
    unsigned char ab[16];
    if (!c->cache.memcached || c->cache.socket || !c->ngx.resolver.n)
        return 0;
    return inet_pton(AF_INET, c->cache.host, ab) != 1 && inet_pton(AF_INET6, c->cache.host, ab) != 1;
}

static void render_upstream(const gqlgw_config *c, const gqlgw_source *s, gql_buf *b)
{
    buf_printf(b, "upstream gqlgw_%s {\n    zone gqlgw_%s 64k;\n", s->name, s->name);
    if (!s->host_is_ip) {
        render_resolver(c, b, "    ");
        buf_printf(b, "    server %s:%d resolve;\n", s->host, s->port);
    } else {
        buf_printf(b, "    server %s:%d;\n", s->host, s->port);
    }
    if (s->keepalive > 0)
        buf_printf(b, "    keepalive %lld;\n    keepalive_timeout %s;\n", (long long)s->keepalive, s->keepalive_timeout);
    buf_puts(b, "}\n\n");
}

static void render_source_location(const gqlgw_config *c, const gqlgw_source *s, gql_buf *b, const char *ind)
{
    uint32_t i;
    buf_printf(b, "%slocation /_src/%s/ {\n", ind, s->name);
    buf_printf(b, "%s    internal;\n%s    proxy_http_version 1.1;\n%s    proxy_set_header Connection \"\";\n", ind, ind, ind);
    buf_printf(b, "%s    proxy_set_header Host ", ind);
    ngx_q(b, s->host_header, 0);
    buf_puts(b, ";\n");
    buf_printf(b, "%s    proxy_set_header Accept-Encoding \"\";\n", ind);
    buf_printf(b, "%s    proxy_set_header Content-Type $gqlgw_ctype;\n", ind);
    if (s->headers_mode == HDR_ALLOW) {
        buf_printf(b, "%s    proxy_pass_request_headers off;\n", ind);
        for (i = 0; i < s->forward_headers.n; i++) {
            if (in_map(&s->set_headers, s->forward_headers.v[i]))
                continue;
            buf_printf(b, "%s    proxy_set_header %s ", ind, s->forward_headers.v[i]);
            http_var(b, s->forward_headers.v[i]);
            buf_puts(b, ";\n");
        }
    } else {
        for (i = 0; i < s->drop_headers.n; i++)
            buf_printf(b, "%s    proxy_set_header %s \"\";\n", ind, s->drop_headers.v[i]);
    }
    if (!in_map(&s->set_headers, "Accept") && !(s->headers_mode == HDR_ALLOW && in_list(&s->forward_headers, "Accept")))
        buf_printf(b, "%s    proxy_set_header Accept \"application/json\";\n", ind);
    for (i = 0; i < s->set_headers.n; i++) {
        buf_printf(b, "%s    proxy_set_header %s ", ind, s->set_headers.k[i]);
        ngx_q(b, s->set_headers.v[i], 1);
        buf_puts(b, ";\n");
    }
    if (c->metrics.enabled)     /* upstream time for gqlgw_upstream_duration_seconds */
        buf_printf(b, "%s    more_set_headers \"X-Gqlgw-Upstream-Time: $upstream_header_time\";\n", ind);
    buf_printf(b, "%s    proxy_connect_timeout %s;\n%s    proxy_send_timeout %s;\n%s    proxy_read_timeout %s;\n", ind,
               s->connect_timeout, ind, s->send_timeout, ind, s->read_timeout);
    if (!strcmp(s->scheme, "https")) {
        if (!s->host_is_ip) {
            buf_printf(b, "%s    proxy_ssl_server_name on;\n%s    proxy_ssl_name ", ind, ind);
            ngx_q(b, s->tls_name, 0);
            buf_puts(b, ";\n");
        }
        if (s->tls_verify) {
            buf_printf(b, "%s    proxy_ssl_verify on;\n%s    proxy_ssl_verify_depth 4;\n%s    proxy_ssl_trusted_certificate ",
                       ind, ind, ind);
            ngx_q(b, s->ca, 0);
            buf_puts(b, ";\n");
        } else {
            buf_printf(b, "%s    proxy_ssl_verify off;\n", ind);
        }
    }
    buf_printf(b, "%s    include ", ind);
    {
        char path[4096];
        snprintf(path, sizeof path, "%s/sources.d/%s/*.conf", c->dir, s->name);
        ngx_q(b, path, 0);
    }
    buf_puts(b, ";\n");
    buf_printf(b, "%s    proxy_pass \"%s://gqlgw_%s%s$gqlgw_path\";\n%s}\n", ind, s->scheme, s->name, s->prefix, ind);
}

static void render_locations(const gqlgw_config *c, gql_buf *b, const char *ind)
{
    uint32_t i;
    buf_printf(b, "%slocation = %s {\n", ind, c->gw.path);
    buf_printf(b, "%s    set $gqlgw_path \"\";\n%s    set $gqlgw_ctype \"\";\n", ind, ind);
    buf_printf(b, "%s    set $gql_rounds \"-\";\n%s    set $gql_subrequests \"-\";\n%s    set $gql_cache \"-\";\n", ind, ind, ind);
    buf_printf(b, "%s    client_max_body_size %s;\n%s    client_body_buffer_size %s;\n", ind, c->gw.max_body.text, ind,
               c->gw.max_body.text);
    if (memcached_needs_resolver(c)) {
        char ind2[32];
        snprintf(ind2, sizeof ind2, "%s    ", ind);
        render_resolver(c, b, ind2);
    }
    if (c->gw.access_log) {
        buf_printf(b, "%s    access_log ", ind);
        if (!strcmp(c->gw.access_log, "off")) {
            buf_puts(b, "off;\n");
        } else {
            ngx_q(b, c->gw.access_log, 0);
            buf_puts(b, " gqlgw;\n");
        }
    }
    buf_printf(b, "%s    content_by_lua_block { require(\"gqlgw\").serve() }\n", ind);
    buf_printf(b, "%s    log_by_lua_block { require(\"gqlgw\").log() }\n%s}\n", ind, ind);
    for (i = 0; i < c->nsources; i++) {
        if (!c->sources[i].host)    /* not resolved (CHECK mode): nothing to render */
            continue;
        buf_putc(b, '\n');
        render_source_location(c, &c->sources[i], b, ind);
    }
}

static void render_admin(const gqlgw_config *c, gql_buf *b)
{
    uint32_t i;
    if (!c->metrics.enabled && !c->purge.enabled)
        return;
    buf_printf(b, "server {\n    listen %s;\n    access_log off;\n", c->metrics.listen);
    if (c->purge.enabled && memcached_needs_resolver(c))
        render_resolver(c, b, "    ");
    for (i = 0; i < c->metrics.allow.n; i++)
        buf_printf(b, "    allow %s;\n", c->metrics.allow.v[i]);
    if (c->metrics.allow.n)
        buf_puts(b, "    deny all;\n");
    if (c->metrics.enabled)
        buf_printf(b, "    location = %s {\n        content_by_lua_block { require(\"gqlgw\").metrics() }\n    }\n",
                   c->metrics.path);
    if (c->purge.enabled)
        buf_printf(b, "    location = %s {\n        content_by_lua_block { require(\"gqlgw\").purge() }\n    }\n",
                   c->purge.path);
    buf_puts(b, "    location / {\n        return 404;\n    }\n}\n");
}

void gqlgw_render_nginx(const gqlgw_config *c, const char *lua_path, const char *src_name, gql_buf *http,
                        gql_buf *locations)
{
    uint32_t i;
    buf_printf(http, "# generated by gqlc render from %s: do not edit\n# include this file inside http { }%s\n\n",
               src_name, locations ? ", and gqlgw.locations.conf inside a server { }" : "");
    if (c->cache.shm_size.bytes > 0)
        buf_printf(http, "lua_shared_dict gqlgw_cache %s;\n", c->cache.shm_size.text);
    if (c->metrics.enabled)
        buf_printf(http, "lua_shared_dict gqlgw_metrics %s;\n", c->metrics.shm_size.text);
    if (c->ngx.init) {
        buf_puts(http, "init_by_lua_block {\n    require(\"gqlgw\").init(");
        lua_str(http, lua_path);
        buf_puts(http, ")\n}\n");
    } else {
        buf_puts(http, "# [nginx] init = false: call require(\"gqlgw\").init(");
        lua_str(http, lua_path);
        buf_puts(http, ") in your init_by_lua\n");
    }
    if (needs_dollar(c))
        buf_puts(http, "geo $gqlgw_dollar {\n    default \"$\";\n}\n");
    if (c->gw.access_log && strcmp(c->gw.access_log, "off"))
        buf_puts(http, "log_format gqlgw '$remote_addr - $remote_user [$time_local] \"$request\" $status '\n"
                       "                 '$body_bytes_sent $request_time rounds=$gql_rounds sub=$gql_subrequests '\n"
                       "                 'cache=$gql_cache';\n");
    buf_putc(http, '\n');
    for (i = 0; i < c->nsources; i++)
        if (c->sources[i].host)
            render_upstream(c, &c->sources[i], http);
    if (locations) {
        buf_printf(locations, "# generated by gqlc render from %s: do not edit\n# include this file inside a server { }\n\n",
                   src_name);
        render_locations(c, locations, "");
    } else {
        buf_printf(http, "server {\n    listen %s;\n    server_name %s;\n\n", c->gw.listen, c->gw.server_name);
        render_locations(c, http, "    ");
        buf_puts(http, "\n    include ");
        {
            char path[4096];
            snprintf(path, sizeof path, "%s/server.d/*.conf", c->dir);
            ngx_q(http, path, 0);
        }
        buf_puts(http, ";\n}\n\n");
    }
    render_admin(c, http);
}
