/* routes.c - emits schema.routes.lua (gateway metadata for the Lua runtime). */
#include "sdl.h"

#include <errno.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

static void lua_str(gql_buf *b, const char *p, size_t n)
{
    size_t i;
    buf_putc(b, '"');
    for (i = 0; i < n; i++) {
        unsigned char c = (unsigned char)p[i];
        if (c == '"' || c == '\\')
            buf_printf(b, "\\%c", c);
        else if (c == '\n')
            buf_puts(b, "\\n");
        else if (c < 0x20 || c == 0x7f)
            buf_printf(b, "\\%03u", c);
        else
            buf_putc(b, (char)c);
    }
    buf_putc(b, '"');
}

static void lua_gstr(gql_buf *b, gql_str s)
{
    lua_str(b, s.p, s.n);
}

static void emit_tpl(gql_buf *b, const gql_tpl_part *p)
{
    int i;
    buf_puts(b, "{ ");
    for (; p; p = p->next) {
        switch (p->kind) {
        case TP_LIT:
            lua_gstr(b, p->lit);
            break;
        case TP_ARGS:
            buf_puts(b, "{ \"args\"");
            for (i = 0; i < p->nsegs; i++) {
                buf_puts(b, ", ");
                lua_gstr(b, p->segs[i]);
            }
            buf_puts(b, " }");
            break;
        case TP_ARGS_ALL:
            buf_puts(b, "{ \"args\" }");
            break;
        case TP_PARENT:
            buf_puts(b, "{ \"parent\", ");
            lua_gstr(b, p->lit);
            buf_puts(b, " }");
            break;
        case TP_KEYS:
            buf_puts(b, "{ \"keys\" }");
            break;
        }
        buf_puts(b, ", ");
    }
    buf_puts(b, "}");
}

static void emit_select(gql_buf *b, gql_str sel)
{
    const char *p = sel.p, *e = sel.p + sel.n;
    buf_puts(b, "{ ");
    while (p < e) {
        const char *q = p;
        while (q < e && *q != '.')
            q++;
        lua_str(b, p, (size_t)(q - p));
        buf_puts(b, ", ");
        p = q + 1;
    }
    buf_puts(b, "}");
}

static void coord(gql_buf *b, const gql_schema *s, uint32_t fi)
{
    const gql_field_rec *f = &s->fields[fi];
    gql_buf t;
    buf_init(&t);
    buf_printf(&t, "%s.%s", GQL_S(s, s->types[f->owner].name), GQL_S(s, f->name));
    lua_str(b, t.p, t.len);
    buf_free(&t);
}

int gql_routes_write(const gql_compiled *c, const char *path, const char *sdl_name, char *err, size_t errn)
{
    const gql_schema *s = gql_compiled_schema(c);
    gql_buf b;
    uint32_t i;
    FILE *f;
    char tmp[4096];

    buf_init(&b);
    buf_puts(&b, "-- generated by gqlc from ");
    buf_puts(&b, sdl_name);
    buf_puts(&b, "; do not edit\nreturn {\n  version = 1,\n");
    buf_printf(&b, "  hash = \"%016llx\",\n", (unsigned long long)s->hash);
    buf_puts(&b, "  fields = {\n");
    for (i = 0; i < gql_compiled_nroutes(c); i++) {
        const gql_route *r = gql_compiled_route(c, i);
        buf_puts(&b, "    [");
        coord(&b, s, r->field);
        buf_puts(&b, "] = {\n      fetch = { source = ");
        lua_gstr(&b, r->source);
        buf_puts(&b, ", method = ");
        lua_gstr(&b, r->method);
        buf_puts(&b, ", path = ");
        emit_tpl(&b, r->path);
        if (r->body) {
            buf_puts(&b, ", body = ");
            emit_tpl(&b, r->body);
        }
        if (r->select.n) {
            buf_puts(&b, ", select = ");
            emit_select(&b, r->select);
        }
        buf_puts(&b, " },\n");
        if (r->has_batch) {
            buf_puts(&b, "      batch = { path = ");
            emit_tpl(&b, r->batch_path);
            buf_puts(&b, ", match = ");
            lua_gstr(&b, r->batch_match);
            buf_printf(&b, ", max = %u", r->batch_max);
            if (r->batch_select.n) {
                buf_puts(&b, ", select = ");
                emit_select(&b, r->batch_select);
            }
            buf_puts(&b, " },\n");
        }
        if (r->cache_ttl >= 0) {
            buf_printf(&b, "      cache = { ttl = %d, scope = ", r->cache_ttl);
            lua_gstr(&b, r->cache_scope);
            buf_puts(&b, " },\n");
        }
        buf_puts(&b, "    },\n");
    }
    buf_puts(&b, "  },\n  from = {\n");
    for (i = 0; i < s->nfields; i++) {
        const gql_str *k = gql_compiled_from(c, i);
        if (!k)
            continue;
        buf_puts(&b, "    [");
        coord(&b, s, i);
        buf_puts(&b, "] = ");
        lua_gstr(&b, *k);
        buf_puts(&b, ",\n");
    }
    buf_puts(&b, "  },\n  discriminators = {\n");
    for (i = 0; i < s->ntypes; i++) {
        const gql_str *k = gql_compiled_discriminator(c, i);
        if (!k)
            continue;
        buf_puts(&b, "    [");
        lua_str(&b, GQL_S(s, s->types[i].name), s->types[i].name.len);
        buf_puts(&b, "] = ");
        lua_gstr(&b, *k);
        buf_puts(&b, ",\n");
    }
    buf_puts(&b, "  },\n}\n");

    snprintf(tmp, sizeof tmp, "%s.tmp.%ld", path, (long)getpid());
    if (b.oom) {
        snprintf(err, errn, "out of memory");
        buf_free(&b);
        return -1;
    }
    f = fopen(tmp, "wb");
    if (!f) {
        snprintf(err, errn, "%s: %s", tmp, strerror(errno));
        buf_free(&b);
        return -1;
    }
    if (fwrite(b.p, 1, b.len, f) != b.len) {
        snprintf(err, errn, "%s: %s", tmp, strerror(errno));
        fclose(f);
        unlink(tmp);
        buf_free(&b);
        return -1;
    }
    if (fclose(f)) {
        snprintf(err, errn, "%s: %s", tmp, strerror(errno));
        unlink(tmp);
        buf_free(&b);
        return -1;
    }
    buf_free(&b);
    if (rename(tmp, path)) {
        snprintf(err, errn, "%s: %s", path, strerror(errno));
        unlink(tmp);
        return -1;
    }
    return 0;
}
