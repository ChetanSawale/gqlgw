#!/bin/sh
# Benchmark: N+1 naive vs @batch vs @batch + @cache (wrk). Writes bench/RESULTS.md.
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
B="$ROOT/build/bench"
NGINX="$ROOT/.deps/openresty/nginx/sbin/nginx"
DURATION="${DURATION:-10s}"
CONNS="${CONNS:-16}"
export BACKEND_LATENCY="${BACKEND_LATENCY:-0.002}"
mkdir -p "$B/logs" "$B/conf"
"$ROOT/build/gqlc" compile -q -o "$B/schema.gqlb" "$ROOT/bench/schema.graphqls"
# METRICS=1: Prometheus metrics on, as rendered by gqlc (to measure their cost)
if [ "${METRICS:-0}" = 1 ]; then
    sed -e "s|@ROOT@|$ROOT|g" \
        -e 's|@METRICS_OPT@|metrics = { shm = "gqlgw_metrics" },|' \
        -e 's|@LOG_BY_LUA@|log_by_lua_block { require("gqlgw").log() }|' \
        -e 's|@UPSTREAM_TIME@|more_set_headers "X-Gqlgw-Upstream-Time: $upstream_header_time";|' \
        "$ROOT/bench/nginx.conf.in" > "$B/conf/nginx.conf"
else
    sed -e "s|@ROOT@|$ROOT|g" -e "s|@METRICS_OPT@||" -e "s|@LOG_BY_LUA@||" -e "s|@UPSTREAM_TIME@||" \
        "$ROOT/bench/nginx.conf.in" > "$B/conf/nginx.conf"
fi
"$NGINX" -p "$B" -c conf/nginx.conf -s stop 2>/dev/null || true
sleep 0.3
"$NGINX" -p "$B" -c conf/nginx.conf
trap '"$NGINX" -p "$B" -c conf/nginx.conf -s stop' EXIT
sleep 0.5

out="${OUT:-$ROOT/bench/RESULTS.md}"
{
    echo "# Benchmark"
    echo
    echo "\`{ posts(limit: 100) { id title <author field> { name } } }\` — 100 posts by 100 distinct authors,"
    echo "backend latency ${BACKEND_LATENCY}s per request, wrk ${DURATION} with ${CONNS} connections,"
    echo "OpenResty 2 workers, $(nproc) CPUs ($(uname -m)), $(date -u +%Y-%m-%d)."
    echo
    echo "| variant | subrequests / query | req/s | latency avg | latency p99 |"
    echo "|---|---|---|---|---|"
} > "$out"

for variant in naiveAuthor author cachedAuthor; do
    q="{ posts(limit: 100) { id title $variant { name } } }"
    # warm-up (fills the cache for cachedAuthor) and subrequest count
    sub=$(curl -s -D - -o /dev/null -H 'Content-Type: application/json' \
          -d "{\"query\": \"$q\"}" http://127.0.0.1:18080/graphql | tr -d '\r' | awk -F': ' 'tolower($1)=="x-gql-subrequests"{print $2}')
    sub2=$(curl -s -D - -o /dev/null -H 'Content-Type: application/json' \
          -d "{\"query\": \"$q\"}" http://127.0.0.1:18080/graphql | tr -d '\r' | awk -F': ' 'tolower($1)=="x-gql-subrequests"{print $2}')
    res=$(QUERY="$q" wrk -t2 -c"$CONNS" -d"$DURATION" --latency -s "$ROOT/bench/post.lua" http://127.0.0.1:18080/graphql)
    rps=$(echo "$res" | awk '/Requests\/sec/{print $2}')
    avg=$(echo "$res" | awk '/Latency/ && !/Distribution/{print $2; exit}')
    p99=$(echo "$res" | awk '$1=="99%"{print $2}')
    errs=$(echo "$res" | awk '/Non-2xx/{print $NF}')
    echo "| \`$variant\` | $sub (then $sub2) | $rps | $avg | $p99 |" >> "$out"
    echo "$variant: subrequests=$sub/$sub2 rps=$rps avg=$avg p99=$p99 ${errs:+non-2xx=$errs}"
done
echo >> "$out"
echo "Generated by \`make bench\` (bench/run.sh)." >> "$out"
cat "$out"
